// Regenerates src/fonts.css and public/font-licenses.txt from the @fontsource-variable packages
// listed below.
//
//   npm run fonts
//
// Each font is registered under its plain name ("Inter", not "Inter Variable") so themes can
// refer to it the way people write font names. Only the Latin, Latin Extended and Cyrillic
// subsets are bundled: they cover the four interface languages. The browser downloads a file
// only when a glyph of that subset is drawn in that font.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

/** [package, family name] — keep in sync with BUNDLED_FONTS in src/lib/themes.ts */
const FONTS = [
  ["inter", "Inter"],
  ["manrope", "Manrope"],
  ["montserrat", "Montserrat"],
  ["nunito", "Nunito"],
  ["rubik", "Rubik"],
  ["exo-2", "Exo 2"],
  ["tektur", "Tektur"],
  ["oswald", "Oswald"],
  ["unbounded", "Unbounded"],
  ["comfortaa", "Comfortaa"],
  ["lora", "Lora"],
  ["playfair-display", "Playfair Display"],
  ["jetbrains-mono", "JetBrains Mono"],
  ["pixelify-sans", "Pixelify Sans"],
];
const SUBSETS = ["cyrillic", "latin-ext", "latin"];

let css =
  "/* Generated by scripts/generate-fonts-css.mjs — do not edit by hand. */\n" +
  "/* Fonts bundled with Kanso (SIL Open Font License), available to every theme by name. */\n";

for (const [pkg, family] of FONTS) {
  const source = readFileSync(`node_modules/@fontsource-variable/${pkg}/wght.css`, "utf8");
  for (const subset of SUBSETS) {
    const file = `${pkg}-${subset}-wght-normal.woff2`;
    const block = source.split("@font-face").find((b) => b.includes(`/${file})`));
    if (!block) throw new Error(`${file} not found in ${pkg}/wght.css`);
    const weight = block.match(/font-weight:\s*([^;]+);/)[1].trim();
    const range = block.match(/unicode-range:\s*([^;]+);/)[1].trim();
    css +=
      `\n@font-face {\n` +
      `  font-family: "${family}";\n` +
      `  font-style: normal;\n` +
      `  font-display: swap;\n` +
      `  font-weight: ${weight};\n` +
      `  src: url("@fontsource-variable/${pkg}/files/${file}") format("woff2-variations");\n` +
      `  unicode-range: ${range};\n` +
      `}\n`;
  }
}

writeFileSync("src/fonts.css", css);

// The fonts are redistributed inside the app, so their license travels with it: this file is
// copied into the bundle by Vite (public/).
let notices =
  "Fonts bundled with Kanso\n========================\n\n" +
  "Each font below is licensed under the SIL Open Font License, Version 1.1, reproduced at the\n" +
  "end of this file.\n\n";
let licenseText = "";
for (const [pkg, family] of FONTS) {
  const license = readFileSync(`node_modules/@fontsource-variable/${pkg}/LICENSE`, "utf8");
  // First line: the copyright notice (some repeat it for the italic file we do not ship)
  const copyright = license.split("\n")[0].split(/ \S+\[[^\]]*\]\.ttf:/)[0].trim();
  notices += `${family}\n  ${copyright}\n\n`;
  licenseText ||= license.slice(license.indexOf("-----------------------------------------------------------"));
}
mkdirSync("public", { recursive: true });
writeFileSync("public/font-licenses.txt", notices + licenseText.trimEnd() + "\n");
console.log(`src/fonts.css: ${FONTS.length} fonts, ${FONTS.length * SUBSETS.length} files`);
